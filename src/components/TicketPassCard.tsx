"use client";

import { useState } from "react";
import { QRCodeSVG } from "qrcode.react";
import { buildQRPayload } from "@/utils/ticketService";
import { Download, CheckCircle2, Ticket, Sparkles, MapPin, Calendar } from "lucide-react";

interface TicketPassCardProps {
  booking: any;
  passes: any[];
}

export default function TicketPassCard({ booking, passes }: TicketPassCardProps) {
  const [activePassIndex, setActivePassIndex] = useState(0);

  // If no issued passes exist yet, show a fallback waiting message
  if (!passes || passes.length === 0) {
    return (
      <div className="rounded-3xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-6 text-center shadow-sm">
        <h3 className="font-bold text-neutral-900 dark:text-white text-base">
          {booking.event?.title || "Event Ticket"}
        </h3>
        <p className="text-xs text-neutral-500 mt-1">
          Your booking is verified. Tickets are being generated by the gate service.
        </p>
      </div>
    );
  }

  const currentPass = passes[activePassIndex] || passes[0];
  const qrValue = buildQRPayload(currentPass, booking.event?.title);

  const downloadQR = () => {
    const svg = document.getElementById(`qr-svg-${currentPass.id}`);
    if (!svg) return;
    const svgData = new XMLSerializer().serializeToString(svg);
    const canvas = document.createElement("canvas");
    const ctx = canvas.getContext("2d");
    const img = new Image();
    img.onload = () => {
      canvas.width = img.width + 40;
      canvas.height = img.height + 40;
      if (ctx) {
        ctx.fillStyle = "#ffffff";
        ctx.fillRect(0, 0, canvas.width, canvas.height);
        ctx.drawImage(img, 20, 20);
        const a = document.createElement("a");
        a.download = `ticket-${currentPass.ticket_code}.png`;
        a.href = canvas.toDataURL("image/png");
        a.click();
      }
    };
    img.src = "data:image/svg+xml;base64," + btoa(svgData);
  };

  return (
    <div className="overflow-hidden rounded-3xl border border-neutral-200/80 dark:border-neutral-800 bg-white dark:bg-neutral-900 shadow-md hover:shadow-lg transition-all flex flex-col relative">
      
      {/* Card Header with Ticket Gradient */}
      <div className="bg-gradient-to-r from-emerald-600 to-teal-600 p-5 text-white relative">
        <div className="flex items-center justify-between gap-2">
          <span className="text-[10px] font-black uppercase tracking-wider bg-black/20 backdrop-blur-md px-2.5 py-0.5 rounded-full border border-white/20">
            {currentPass.ticket_type || "Standard"} Pass
          </span>
          {booking.event?.event_number && (
            <span className="text-xs font-bold bg-white/20 px-2 py-0.5 rounded-md backdrop-blur-md">
              #{booking.event.event_number}
            </span>
          )}
        </div>
        <h3 className="mt-2 text-base sm:text-lg font-black tracking-tight line-clamp-1">
          {booking.event?.title || "Event Pass"}
        </h3>
        <p className="text-xs text-emerald-100 mt-1 flex items-center gap-1.5 line-clamp-1">
          <Calendar className="w-3.5 h-3.5 shrink-0" />
          <span>{booking.event?.start_date ? new Date(booking.event.start_date).toLocaleDateString() : "Date TBD"}</span>
          <span>•</span>
          <span className="truncate">{booking.event?.venue_name || "Venue TBD"}</span>
        </p>
      </div>

      {/* Multiple Tickets Tab Switcher (if user booked > 1 ticket) */}
      {passes.length > 1 && (
        <div className="p-2.5 bg-neutral-100 dark:bg-neutral-950/80 border-b border-neutral-200 dark:border-neutral-800 flex items-center justify-center gap-1.5 overflow-x-auto">
          {passes.map((pass, index) => {
            const isSelected = index === activePassIndex;
            return (
              <button
                key={pass.id}
                onClick={() => setActivePassIndex(index)}
                className={`px-3 py-1 rounded-lg text-xs font-bold transition flex items-center gap-1.5 shrink-0 cursor-pointer ${
                  isSelected
                    ? "bg-emerald-600 text-white shadow-xs"
                    : "bg-white dark:bg-neutral-800 text-neutral-600 dark:text-neutral-400 hover:text-neutral-900 dark:hover:text-white"
                }`}
              >
                <span>Pass {index + 1} of {passes.length}</span>
                {pass.status === "used" && (
                  <span className="h-1.5 w-1.5 rounded-full bg-neutral-400"></span>
                )}
              </button>
            );
          })}
        </div>
      )}

      {/* QR Code and Pass Details */}
      <div className="p-6 flex flex-col items-center justify-center text-center">
        
        {/* Pass Status Banner */}
        <div className="mb-4">
          {currentPass.status === "used" ? (
            <span className="inline-flex items-center gap-1.5 rounded-full bg-neutral-100 dark:bg-neutral-800 px-3 py-1 text-xs font-bold text-neutral-500 border border-neutral-200 dark:border-neutral-700">
              <span>✓</span> Used / Checked-in at Gate
            </span>
          ) : (
            <span className="inline-flex items-center gap-1.5 rounded-full bg-emerald-100 dark:bg-emerald-950/60 px-3 py-1 text-xs font-bold text-emerald-800 dark:text-emerald-300 border border-emerald-200 dark:border-emerald-800">
              <span className="h-2 w-2 rounded-full bg-emerald-500 animate-pulse"></span>
              Ready for Gate Scanner (Admit 1)
            </span>
          )}
        </div>

        {/* The QR Code Container */}
        <div className="p-4 bg-white rounded-2xl border-2 border-neutral-100 dark:border-neutral-800 shadow-sm inline-block">
          <QRCodeSVG
            id={`qr-svg-${currentPass.id}`}
            value={qrValue}
            size={170}
            level="M"
            marginSize={2}
          />
        </div>

        {/* Ticket Code & Attendee */}
        <div className="mt-4">
          <div className="font-mono text-sm font-black text-neutral-900 dark:text-white tracking-widest bg-neutral-100 dark:bg-neutral-800 px-3 py-1 rounded-lg inline-block">
            {currentPass.ticket_code}
          </div>
          <p className="text-xs text-neutral-500 dark:text-neutral-400 mt-1.5">
            Holder: <strong className="text-neutral-900 dark:text-white">{currentPass.holder_name}</strong>
          </p>
        </div>

        {/* Action Button */}
        <div className="mt-5 w-full flex items-center justify-center gap-2">
          <button
            onClick={downloadQR}
            className="w-full max-w-xs rounded-xl bg-neutral-100 hover:bg-neutral-200 dark:bg-neutral-800 dark:hover:bg-neutral-700 text-neutral-800 dark:text-neutral-200 py-2.5 text-xs font-bold transition flex items-center justify-center gap-2 shadow-xs cursor-pointer"
          >
            <Download className="w-4 h-4" />
            <span>Download High-Res QR Ticket</span>
          </button>
        </div>

      </div>

      {/* Card Footer Tear-off Style */}
      <div className="px-5 py-3 bg-neutral-50 dark:bg-neutral-950/80 border-t border-dashed border-neutral-200 dark:border-neutral-800 flex items-center justify-between text-[11px] text-neutral-400 font-medium">
        <span>Single Entry Cryptographic Pass</span>
        <span>Ticket {currentPass.ticket_number} of {currentPass.total_tickets}</span>
      </div>

    </div>
  );
}
